"""Build the public website from the agents' data.

  py website/build.py           reads data/       and writes the site to docs/
  py website/build.py --mock    reads data-mock/  and writes docs-mock/ (never published)

It only READS the data (the knowledge base is opened read-only) and writes plain HTML,
CSS and JSON files. Publishing is committing docs/ and pushing (GitHub Pages serves it).
"""

import argparse
import json
import shutil
import sqlite3
import sys
import tomllib
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:          # allow running this file directly
    sys.path.insert(0, str(ROOT))

from core import integrity              # noqa: E402
from knowledge.db import KnowledgeBase  # noqa: E402
from website import feed, pages         # noqa: E402

MARKER = ".generated-by-website-build"  # the builder only ever replaces a folder it made


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def prepare_output(out_dir: Path) -> None:
    if out_dir.exists() and any(out_dir.iterdir()):
        if not (out_dir / MARKER).exists():
            raise SystemExit(f"{out_dir} contains files the website builder did not make; "
                             "refusing to replace it.")
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / MARKER).write_text("This folder is generated by website/build.py.\n", encoding="utf-8")
    (out_dir / ".nojekyll").write_text("", encoding="utf-8")   # GitHub Pages: serve files as they are


def build(data_dir: Path, out_dir: Path, config: dict) -> dict:
    """Build the whole site. Returns a short summary."""
    db_path = data_dir / "knowledge.db"
    if not db_path.exists():
        raise SystemExit(f"No knowledge base in {data_dir} yet. Run some cycles first.")
    kb = KnowledgeBase(db_path, read_only=True)
    try:
        chain_rows = kb.conn.execute(
            "SELECT number, prev_hash, log_hash, log_json FROM cycles ORDER BY number").fetchall()
    except sqlite3.OperationalError:
        raise SystemExit("The knowledge base needs its one-time upgrade: run  py run.py --verify")

    settings = config.get("site", {})
    findings = kb.findings()
    logs = kb.cycle_logs()
    chain = [{"number": n, "prev_hash": prev, "log_hash": h, "log": json.loads(log_json)}
             for n, prev, h, log_json in chain_rows]
    roadmap_file = data_dir / "roadmap.json"
    roadmap = json.loads(roadmap_file.read_text(encoding="utf-8")) if roadmap_file.exists() else {}
    versions = []
    for f in sorted((data_dir / "roadmap_versions").glob("v*.json")):
        v = json.loads(f.read_text(encoding="utf-8"))
        versions.append({"version": v["version"], **v["changes_in_this_version"]})

    site = {
        "title": settings.get("title", "Absolute Truth"),
        "tagline": settings.get("tagline", ""),
        "repo_url": settings.get("repo_url", ""),
        "site_url": settings.get("site_url", ""),
        "built_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "rules": integrity.rules_in_force(),
        "cycle_count": len(logs),
    }

    prepare_output(out_dir)
    shutil.copy(ROOT / "website" / "style.css", out_dir / "style.css")
    shutil.copy(ROOT / "website" / "verify_chain.py", out_dir / "verify_chain.py")

    updates = kb.public_updates()
    _write(out_dir / "index.html", pages.home(site, roadmap, findings, logs, updates))
    _write(out_dir / "updates.html", pages.updates_page(site, updates))
    _write(out_dir / "roadmap.html", pages.roadmap_page(site, roadmap, versions))
    _write(out_dir / "findings.html", pages.findings_page(site, findings))
    _write(out_dir / "path.html", pages.path_page(site, logs))
    _write(out_dir / "verify.html", pages.verify_page(site, chain))
    if site["site_url"]:
        _write(out_dir / "feed.xml", feed.atom(site, findings, logs, updates))

    findings_data = []
    for f in findings:
        dependents, events = kb.dependents(f["id"]), kb.events(f["id"])
        _write(out_dir / "findings" / f"{f['id']}.html",
               pages.finding_detail(site, f, dependents, events))
        findings_data.append({**f, "needed_by": dependents, "history": events})

    transcripts = 0
    by_number = {c["number"]: c for c in chain}
    for log in logs:
        n = log["cycle"]
        transcript_file = (data_dir / "runs" / str(log.get("run_id")) / f"cycle_{n:04d}"
                           / "transcript.json")
        publish = settings.get("publish_transcripts", True) and transcript_file.exists()
        if publish:
            transcript = json.loads(transcript_file.read_text(encoding="utf-8"))
            _write(out_dir / "cycles" / f"{n:04d}-transcript.html",
                   pages.transcript_page(site, log, transcript))
            transcripts += 1
        _write(out_dir / "cycles" / f"{n:04d}.html",
               pages.cycle_detail(site, log, by_number.get(n, {}), publish))

    core = ROOT / "core"
    _write(out_dir / "rules.html", pages.rules_page(
        site, (core / "constitution.md").read_text(encoding="utf-8"),
        (core / "CHANGELOG.md").read_text(encoding="utf-8"),
        (core / "limits.toml").read_text(encoding="utf-8")))

    _write(out_dir / "data" / "cycles.json", json.dumps(chain, indent=1, ensure_ascii=False))
    _write(out_dir / "data" / "findings.json", json.dumps(findings_data, indent=1, ensure_ascii=False))
    return {"findings": len(findings), "cycles": len(logs), "transcripts": transcripts,
            "out_dir": str(out_dir)}


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the public website (read-only).")
    parser.add_argument("--mock", action="store_true", help="build from data-mock/ into docs-mock/")
    args = parser.parse_args()
    config = tomllib.loads((ROOT / "config.toml").read_text(encoding="utf-8"))
    data_dir = ROOT / ("data-mock" if args.mock else "data")
    out_dir = ROOT / ("docs-mock" if args.mock else "docs")
    summary = build(data_dir, out_dir, config)
    print(f"Website built in {summary['out_dir']}: {summary['cycles']} cycles, "
          f"{summary['findings']} findings, {summary['transcripts']} transcripts.")
    print(f"Open {out_dir / 'index.html'} in your browser to preview it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
